-- Esquema PostgreSQL de CineManager.
-- Los nombres fisicos se guardan en minusculas para evitar comillas
-- en las consultas. La API devuelve alias con los nombres esperados
-- por el Frontend React (IdGenero, Nombre, Estado, etc.).

CREATE TABLE IF NOT EXISTS genero (
    idgenero INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    fechacreacion TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fechaactualizacion TIMESTAMP WITHOUT TIME ZONE NULL,
    descripcion VARCHAR(500) NULL
);

CREATE TABLE IF NOT EXISTS director (
    iddirector INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(150) NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    fechacreacion TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fechaactualizacion TIMESTAMP WITHOUT TIME ZONE NULL
);

CREATE TABLE IF NOT EXISTS productora (
    idproductora INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    fechacreacion TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fechaactualizacion TIMESTAMP WITHOUT TIME ZONE NULL,
    slogan VARCHAR(250) NULL,
    descripcion VARCHAR(500) NULL
);

CREATE TABLE IF NOT EXISTS tipo (
    idtipo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    fechacreacion TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fechaactualizacion TIMESTAMP WITHOUT TIME ZONE NULL,
    descripcion VARCHAR(500) NULL
);

CREATE TABLE IF NOT EXISTS media (
    idmedia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    serial VARCHAR(50) NOT NULL UNIQUE,
    titulo VARCHAR(200) NOT NULL,
    sinopsis TEXT NULL,
    url VARCHAR(850) NOT NULL UNIQUE,
    imagenportada VARCHAR(2048) NULL,
    fechacreacion TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fechaactualizacion TIMESTAMP WITHOUT TIME ZONE NULL,
    anioestreno SMALLINT NOT NULL CHECK (anioestreno >= 1),
    idgenero INTEGER NOT NULL REFERENCES genero(idgenero) ON UPDATE CASCADE ON DELETE RESTRICT,
    iddirector INTEGER NOT NULL REFERENCES director(iddirector) ON UPDATE CASCADE ON DELETE RESTRICT,
    idproductora INTEGER NOT NULL REFERENCES productora(idproductora) ON UPDATE CASCADE ON DELETE RESTRICT,
    idtipo INTEGER NOT NULL REFERENCES tipo(idtipo) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_media_idgenero ON media(idgenero);
CREATE INDEX IF NOT EXISTS idx_media_iddirector ON media(iddirector);
CREATE INDEX IF NOT EXISTS idx_media_idproductora ON media(idproductora);
CREATE INDEX IF NOT EXISTS idx_media_idtipo ON media(idtipo);

-- Tipos basicos que usa el formulario de Media.
INSERT INTO tipo (nombre, descripcion)
SELECT datos.nombre, datos.descripcion
FROM (VALUES
    ('Película', 'Producción cinematográfica'),
    ('Serie', 'Producción episódica')
) AS datos(nombre, descripcion)
WHERE NOT EXISTS (
    SELECT 1 FROM tipo existente WHERE existente.nombre = datos.nombre
);
